  await page.getByLabel('Synthetic 8 live stream', { exact: true }).selectOption('auto')
  await page.getByText('Playback settings', { exact: true }).click()
  assert.equal(await page.getByRole('checkbox', { name: 'Sync cameras', exact: true }).isChecked(), false)
  await page.waitForFunction(() => [...document.querySelectorAll('.playback-track input')].every(input => !input.disabled))
  assert.equal(await page.locator('.dvr-player').count(), 0)
  const seek = async (card, timestamp) => card.locator('.playback-track input').evaluate((input, value) => { input.value = String(value); input.dispatchEvent(new Event('change', { bubbles: true })) }, timestamp)
  await first.locator('.saving').waitFor()
  await page.clock.fastForward(5000)
  const savingBounds = await first.locator('.saving').evaluate(el => ({ right: el.getBoundingClientRect().right, edge: el.parentElement.getBoundingClientRect().right }))
  assert.ok(Math.abs(savingBounds.right - savingBounds.edge) < 1, 'saving remains flush with live between coverage snapshots')
  const gapStyle = await first.locator('.missing').first().evaluate(el => getComputedStyle(el).backgroundImage)
  assert.ok(gapStyle.includes('135deg') && gapStyle.includes('153, 73, 81'), 'missing data uses a dark-red diagonal hatch')
  await seek(first, now - 60)
  await first.locator('.dvr-player').waitFor()
  await seek(first, now + 2)
  await page.waitForFunction(() => document.querySelectorAll('.dvr-player').length === 0)
  assert.equal(await first.locator('.dashboard-replay-badge').count(), 0, 'new live-side saving tail jumps live, not into a false gap')
  const originalBounds = await first.locator('.playback-track input').evaluate(input => [input.min, input.max])
  await seek(first, now - 230)
  const clickedBounds = await first.locator('.playback-track input').evaluate(input => [input.min, input.max])
  assert.ok(Math.abs(Number(clickedBounds[0]) - Number(originalBounds[0])) <= 1 && Number(clickedBounds[1]) - Number(clickedBounds[0]) === 300, 'left-edge selection does not move timeline markers (apart from the live clock ticking)')
  await first.getByRole('button', { name: 'Go Live', exact: true }).click()
  await seek(first, now - 60)
  await first.locator('.dvr-video.active').waitFor()
  await page.waitForFunction(() => document.querySelector('.camera-card .dvr-video.active')?.readyState >= 3)
  assert.equal(await first.locator('video').count(), 1, 'dashboard replay mounts only one decoder-bearing video element')
  assert.equal(await second.locator('.dvr-player').count(), 0)
  assert.equal(await first.locator('img').count(), 0, 'live JPEG is replaced, not hidden behind DVR')
  const sliderBox = await first.locator('.playback-track input').boundingBox()
  await page.mouse.move(sliderBox.x + sliderBox.width * .4, sliderBox.y + sliderBox.height / 2)
