  assert.equal(frozenState.filter, 'blur(8px)', 'stale frame is visibly blurred behind seeking status')
  assert.equal(await first.locator('video').count(), 1, 'segment change does not add a second video element')
  await first.locator('.dvr-video.active').evaluate(video => video.dispatchEvent(new Event('timeupdate')))
  assert.equal(Number(await first.locator('.playback-track input').inputValue()), now - 170, 'old video updates cannot snap the cursor back during a segment seek')
  releaseSegment()
  await page.waitForFunction(() => document.querySelector('.camera-card .dvr-video.active')?.getAttribute('src') === '/dvr/segment/1')
  await first.locator('.dvr-seeking').waitFor({ state: 'hidden' })
  assert.equal(await first.locator('.dvr-frozen-frame').evaluate(canvas => canvas.width), 0, 'snapshot bitmap is released when the target frame is ready')
  const seekEvidence = await page.evaluate(() => Object.values(window._witnessDiag ?? {}).flatMap(d => d.snapshot().events ?? []).filter(e => e.type === 'seekReady'))
  assert.ok(seekEvidence.some(event => event.segmentId === 1 && event.requestedTimestamp === now - 170 && event.readyState >= 2), 'DVR diagnostics tie decoded seek readiness to the requested timestamp and segment')
  await page.unroute('**/dvr/segment/1')
  await seek(first, now - 60)
  await page.waitForFunction(() => document.querySelector('.camera-card .dvr-video.active')?.getAttribute('src') === '/dvr/segment/2')
  await page.route('**/dvr/segment/1', route => route.fulfill({ status: 404, body: 'missing' }))
  await seek(first, now - 170)
  await first.getByRole('alert').waitFor()
  assert.equal(await first.locator('.dvr-seeking').count(), 0, 'decoder/load failure ends the spinner')
  assert.equal(await first.getByRole('button', { name: 'Retry', exact: true }).count(), 1)
  await page.unroute('**/dvr/segment/1')
  await first.getByRole('button', { name: 'Retry', exact: true }).click()
  await first.getByRole('alert').waitFor({ state: 'hidden' })
  await first.locator('.dvr-seeking').waitFor({ state: 'hidden' })
  await page.waitForFunction(() => document.querySelector('.camera-card .dvr-video.active')?.getAttribute('src') === '/dvr/segment/1')
  await seek(first, now - 60)
  await first.locator('.dvr-seeking').waitFor({ state: 'hidden' })
  await mkdir('test-screenshots', { recursive: true })
  await page.screenshot({ path: 'test-screenshots/dashboard-playback-independent.png', fullPage: true })
  await first.getByRole('button', { name: 'Pause replay', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.dvr-video.active')?.paused)
  await first.getByRole('button', { name: 'Other back amounts' }).click()
  await first.getByRole('button', { name: 'Back 10s', exact: true }).click()
  await first.getByRole('button', { name: 'Other forward amounts' }).click()
  await first.getByRole('button', { name: 'Forward 10s', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Sync cameras', exact: true }).check()
  await second.locator('.dvr-video.active').waitFor()
  await page.waitForFunction(() => [...document.querySelectorAll('.dvr-video.active')].every(v => v.readyState >= 3 && v.paused))
  const times = await page.locator('.dvr-video.active').evaluateAll(videos => videos.map(v => v.currentTime))
  assert.ok(Math.abs(times[0] - times[1]) < 1.5, JSON.stringify(times))
  await seek(first, now - 110)
  await page.waitForFunction(() => [...document.querySelectorAll('.dvr-error')].filter(el => el.textContent.includes('No recording')).length === 2)
  assert.equal(await first.locator('.dvr-error').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(0, 0, 0)', 'missing footage must obscure any stale decoded frame')
  assert.equal(await page.locator('.dashboard-replay-badge').count(), 2)
  await seek(first, now - 10)
  await page.waitForFunction(() => document.querySelectorAll('.dvr-player').length === 0)
  assert.equal(await page.locator('.dashboard-replay-badge').count(), 0, 'saving region jumps both synced cameras live')
  await page.getByRole('checkbox', { name: 'Sync cameras', exact: true }).uncheck()
